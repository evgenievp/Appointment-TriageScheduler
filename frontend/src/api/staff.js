import { request } from './client';

// Записване по телефона от регистратурата. Редът е задържане, после прехвърляне:
// служителят първо запазва часа за себе си (`bookSlot` от `appointments.js`),
// после му праща триажа, и чак накрая го дава на пациента. Триажът трябва да е
// преди прехвърлянето — `TriageService.submitTriage` сверява пациента на
// резервацията с викащия, тоест след прехвърлянето служителят получава 403.

// List<UserDto>: [{ id, name, phone, email }] — **списък**, не един пациент.
// `users.phone` няма уникален индекс и регистрацията не проверява за дубликат,
// тоест няколко профила с един номер са нормален случай: семейство с общ телефон,
// родител, вписан на две деца. Затова телефонът не идентифицира човек и изборът
// кой е насреща е на служителя.
//
// Празен списък значи „няма такъв“. Ненамерен може да дойде и като грешка —
// сървърът невинаги различава празен резултат от повреда — затова викащият
// третира двете еднакво: пътят напред е ръчно въведени име и телефон.
//
// Номерът се праща в E.164; този ендпойнт не нормализира входа (за разлика от
// `assign`), тоест номер с интервали не би намерил нищо.
export const findPatientsByPhone = async (phone) => {
  const found = await request(`/staff/patient/${encodeURIComponent(phone)}`);
  if (Array.isArray(found)) return found;
  return found ? [found] : [];
};

// AppointmentDto. Прехвърля задържания час на пациента.
//
// Субектът се подава в тялото, в едно от двете състояния — точно едно от тях:
//
//   { patientId: 17 }                                  регистриран
//   { name: "Иван Петров", phone: "+359888123456" }    без профил
//
// `patientId`, а не телефон: един номер може да води до няколко профила (няма
// уникален индекс върху `users.phone`), тоест телефонът не идентифицира човек.
// Търсенето вече е върнало точния ред — праща се неговото ид.
//
// Тялото, а не query параметри: телефонът в URL влиза в логовете на сървъра, в
// историята на браузъра и в междинните proxy-та, а за име няма как да се разчита
// на дължината на адреса.
//
// Разминаване с бекенда, мокнато е договореното: контролерът още е с
// `@RequestParam` и няма `@RequestBody`, тоест срещу истинския сървър тялото се
// подминава и `findById(null)` гърми. Работи чак когато приемат тяло.
export const assignSlot = (slotId, subject) =>
  request(`/staff/slots/${slotId}/assign`, {
    method: 'PUT',
    body: JSON.stringify(subject),
  });

// Повишаване на роля. Няма ендпойнт за търсене на потребител по имейл, тоест
// самото повишаване е и проверката: 404 значи „няма такъв“.
//
// Двата метода са различни, както са в контролера — `PATCH` за персонал и `PUT`
// за лекар. Едното е смяна на едно поле, другото създава и ред в `doctor`.

// UserDto
export const promoteToStaff = (email) =>
  request('/staff/promoteToStaff', { method: 'PATCH', body: JSON.stringify({ email }) });

// DoctorDto
export const promoteToDoctor = (email, speciality) =>
  request('/staff/promoteToDoctor', {
    method: 'PUT',
    body: JSON.stringify({ email, speciality }),
  });
