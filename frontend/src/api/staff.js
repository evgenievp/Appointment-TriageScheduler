import { request } from './client';

// Записване по телефона от регистратурата. Редът е задържане, после прехвърляне:
// служителят първо запазва часа за себе си (`bookSlot` от `appointments.js`),
// после му праща триажа, и чак накрая го дава на пациента. Триажът трябва да е
// преди прехвърлянето — `TriageService.submitTriage` сверява пациента на
// резервацията с викащия, тоест след прехвърлянето служителят получава 403.

// UserDto[]: { id, name, phone, email }
//
// Днес връща празен списък за всеки вход, не защото пациентът го няма. Заявката
// е `RIGHT(u.phone, 5) = :lastFiveDigits`, а `normalizePhone` винаги връща низ,
// започващ с `+` — двете не могат да съвпаднат. Провалът е тих: 200 с празен
// масив. Пращаме E.164, за да работи веднага щом сложат `findByPhone`.
export const findPatientsByPhone = (phone) =>
  request(`/staff/patient/${encodeURIComponent(phone)}`);

// AppointmentDto. Прехвърля задържания час на пациента.
//
// Нерегистрираният не получава профил: `User.email` и `password` са
// `nullable = false`, а и регистратурата няма работа да прави акаунти. Затова
// името и телефонът стоят върху самата резервация.
//
// Регистриран: { patientId } — резервацията минава при него и той си я вижда в
// профила. Нерегистриран: { name, phone } — часът остава на служителя, но носи
// име и телефон, за да има кого да повикат.
//
// Днешният контролер не приема нищо от това: взима пациента от
// `authentication.getName()`, тоест прехвърля на самия викащ, и пипа само
// `slot.patientId`, докато `Appointment.patient_id` остава на служителя.
export const assignSlot = (slotId, target) =>
  request(`/staff/slots/${slotId}/assign`, {
    method: 'PUT',
    body: JSON.stringify(target),
  });
